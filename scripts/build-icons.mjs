// Dev-time tool (not part of the build): regenerates the icon shapes in styles/site.css from the icon names used in lib/icons.mjs
// and writes the card -> icon review list. Needs the Lucide SVG files:
//   npm i --no-save lucide-static && node scripts/build-icons.mjs [path/to/lucide-static/icons]
import fs from "fs";
import path from "path";
import { allIcons, addIcons } from "../lib/icons.mjs";

const src = process.argv[2] || "node_modules/lucide-static/icons";
const rules = allIcons().map((n) => {
  const f = path.join(src, n + ".svg");
  if (!fs.existsSync(f)) throw new Error("no such Lucide icon: " + n);
  const inner = fs.readFileSync(f, "utf8").replace(/<!--[\s\S]*?-->/g, "").replace(/<svg[\s\S]*?>|<\/svg>/g, "").replace(/\s+/g, " ").replace(/> </g, "><").replace(/ \/>/g, "/>").trim();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
  return `.ic--${n}{--i:url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/</g, "%3C").replace(/>/g, "%3E").replace(/#/g, "%23")}")}`;
});
// Lucide icons, ISC licence (https://lucide.dev/license)
const cssFile = "styles/site.css", css = fs.readFileSync(cssFile, "utf8");
const A = "/* icons:start (generated by scripts/build-icons.mjs; Lucide, ISC licence) */", Z = "/* icons:end */";
if (!css.includes(A) || !css.includes(Z)) throw new Error("icon markers missing in " + cssFile);
fs.writeFileSync(cssFile, css.slice(0, css.indexOf(A) + A.length) + "\n" + rules.join("\n") + "\n" + css.slice(css.indexOf(Z)));

const seen = [], rows = [];
for (const f of fs.readdirSync("content/pages")) { const s = []; addIcons(fs.readFileSync("content/pages/" + f, "utf8"), s); s.forEach((r) => rows.push([f.replace(".html", ""), ...r])); seen.push(...s); }
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;
fs.writeFileSync("digitalwebweaver-audit/card-icons.csv", "﻿Page file,Card type,Card title,Icon\n" + rows.map((r) => r.map(q).join(",")).join("\n"));
const fb = seen.filter((r) => ["layers", "sparkles", "target", "puzzle"].includes(r[2]));
const count = {}; seen.forEach((r) => (count[r[2]] = (count[r[2]] || 0) + 1));
console.log(`icons: ${rules.length}, ${rules.join("").length} bytes of CSS | cards: ${seen.length} | generic fallback: ${fb.length}`);
console.log("most used:", Object.entries(count).sort((a, b) => b[1] - a[1]).slice(0, 12).map((e) => e.join(" ")).join(", "));
console.log("fallback titles:", [...new Set(fb.map((r) => r[1]))].join(" | "));
